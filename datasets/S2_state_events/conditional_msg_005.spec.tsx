import React from 'react';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import App from './App';

describe('S2 state+events: conditional_msg_005', () => {
  it('updates state on action', async () => {
    const user = userEvent.setup();
    render(<App />);
    await user.click(screen.getByRole('button', { name: /cm005-show/i }));
    expect(screen.getByText(/cm005-message/i)).toBeInTheDocument();
  });
});
