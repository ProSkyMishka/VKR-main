import React from 'react';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import App from './App';

describe('S2 state+events: wizard_steps_003', () => {
  it('updates state on action', async () => {
    const user = userEvent.setup();
    render(<App />);
    await user.click(screen.getByRole('button', { name: /wz003-next/i }));
    expect(screen.getByText(/wz003-second/i)).toBeInTheDocument();
  });
});
