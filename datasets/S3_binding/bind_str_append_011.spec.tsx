import React from 'react';
import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import App from './App';

describe('S3 binding: bind_str_append_011', () => {
  it('child action updates parent', async () => {
    const user = userEvent.setup();
    render(<App />);
    await user.click(screen.getByRole('button', { name: /bsa011-append/i }));
    expect(screen.getByText(/bsa011-initx/i)).toBeInTheDocument();
  });
});
